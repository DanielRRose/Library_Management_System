    // methods to insert values into user table
    public void insertSignupDetaisl() {
        String name = txtFieldUserName.getText();
        String pwd = txtFieldPassword.getText();

        try {
            Connection conn = DBConnection.getConnection();
            String sql = "INSERT INTO library_ms.users (username, password) VALUES(?,?)";

            PreparedStatement prepStatement = conn.prepareStatement(sql);
            prepStatement.setString(1, name);
            prepStatement.setString(2, pwd);

            int updatedRowCount = prepStatement.executeUpdate();

            if (updatedRowCount > 0) {
                JOptionPane.showMessageDialog(this, "User Successfuly Created");
                txtFieldUserName.setText("");
                txtFieldUserName.setForeground(getForeground());
                txtFieldPassword.setText("");
            } else {
                JOptionPane.showMessageDialog(this, "Unable to Create new user");
            }
        } catch (SQLException e) {
            e.printStackTrace();
        }
    }

