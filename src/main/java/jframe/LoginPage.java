    // validate login fields
    public boolean LoginFieldsFilled() {
        boolean allFieldFilled = false;
        String username = txtFieldUserName.getText();
        String password = txtFieldPassword.getText();

        if (username.equals("")) {
            JOptionPane.showMessageDialog(this, "Please Enter Username");
            allFieldFilled = false;
        } else if (password.equals("")) {
            JOptionPane.showMessageDialog(this, "Please Enter Password");
            allFieldFilled = false;
        } else {
            allFieldFilled = true;
        }
        return allFieldFilled;
    }

    // validate login credentials
    public void validateLogin() {
        String username = txtFieldUserName.getText();
        String password = txtFieldPassword.getText();

        try {
            Connection conn = DBConnection.getConnection();

            String sqlQuery = "SELECT * FROM library_ms.users WHERE username = ? and password = ?";

            PreparedStatement prepStatment = conn.prepareStatement(sqlQuery);
            prepStatment.setString(1, username);
            prepStatment.setString(2, password);

            ResultSet rs = prepStatment.executeQuery();

            if (rs.next()) {
                HomePage home = new HomePage();
                home.setVisible(true);
                this.dispose();
                // TODO: call HomePage
            } else {
                JOptionPane.showMessageDialog(this, "Invalid Username or Password");
            }

        } catch (Exception e) {
            e.printStackTrace();
        }
    }

    // check duplicate users
    public boolean checkDuplicateUser() {
        boolean userExists = false;
        String username = txtFieldUserName.getText();

        try {
            Connection conn = DBConnection.getConnection();

            String sqlQuery = "SELECT * FROM library_ms.users WHERE username = ?";
            PreparedStatement prepStatment = conn.prepareStatement(sqlQuery);
            prepStatment.setString(1, username);
            ResultSet rs = prepStatment.executeQuery();
            if (rs.next()) {
                userExists = true;
            }
        } catch (SQLException e) {
            e.printStackTrace();
        }
        return userExists;
    }

